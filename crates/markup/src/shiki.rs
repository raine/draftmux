//! The languages Slack highlights in code blocks: shiki's bundled languages
//! (MIT, Copyright (c) 2021 Pine Wu, 2023 Anthony Fu), which Slack renders
//! with. Generated from shiki 4.6.0's `bundledLanguagesInfo`: every `id` and
//! `aliases` entry mapped to the language's `name`, sorted by key.

/// The name Slack shows for code in `lang`, if shiki knows the id or alias.
/// Case matters, as in Slack.
pub fn name(lang: &str) -> Option<&'static str> {
    LANGUAGES
        .binary_search_by(|(key, _)| key.cmp(&lang))
        .ok()
        .map(|ix| LANGUAGES[ix].1)
}

